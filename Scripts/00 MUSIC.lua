function CHGetCategory(mode)
	
	if (GAMESTATE:GetCurrentSong() == nil) then return "NEW TUNES"; end;
	
	local cat = GAMESTATE:GetCurrentSong():GetCategory();
	local path
	if (mode == 1) then
		if (cat ~= "") then
			return cat
		else
			local gn = GAMESTATE:GetCurrentSong():GetGenre()
			if gn ~= "" then
				path = gn
			else
				path = "NEWTUNES"
			end
		end
	else
		if cat ~= "" then
			path = sCategoryText[cat]
		else
			local gn = GAMESTATE:GetCurrentSong():GetGenre()
			if gn ~= "" then
				if sCategoryText[gn] ~= nil then
					path = sCategoryText[gn];
				else
					path = gn;
				end;
			else
				path = "NEW TUNES"
			end
		end
	end
	
	return path
end

