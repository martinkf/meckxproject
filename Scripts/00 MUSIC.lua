    local part1, part2 = _bpm:match("([^%-]+)%-([^%-]+)");
		if part1 and part2 then
			local retA, retB = math.floor(tonumber(part1) or 0), math.floor(tonumber(part2) or 0)
			retA = retA == 0 and "???" or retA;
			retB = retB == 0 and "???" or retB;
				return retA .. "-" .. retB
		end
    return _bpm
