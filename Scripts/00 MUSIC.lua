function CHGetDescription()
	
	local path
	if (GAMESTATE:GetCurrentSong() == nil) then
		return ""
	end;
	local artist = GAMESTATE:GetCurrentSong():GetDisplayArtist()
	if ( artist ~= nil and (artist ~= "Unknown artist" and string.len(artist) > 1) ) then
		path = artist;
	else
		if GAMESTATE:GetFilterOne() == 'FilterOne_Double' then
			path = gLANG() .. GAMESTATE:GetCurrentSong():GetDisplayMainTitle() .. "_D"
		elseif GAMESTATE:GetFilterOne() == 'FilterOne_Single' then
			path = gLANG() .. GAMESTATE:GetCurrentSong():GetDisplayMainTitle() .. "_S"
		else
			path = gLANG() .. GAMESTATE:GetCurrentSong():GetDisplayMainTitle()
		end;
		
		if (sChanDescription[path] ~= nil) then
			path = sChanDescription[path]
		else
			--path = sChanDescription[gLANG() .. "G3N3R1C"] .. GetFixedChannelName(GAMESTATE:GetCurrentSong():GetDisplayMainTitle()) .. "."
			path =string.upper(GetFixedChannelName(GAMESTATE:GetCurrentSong():GetDisplayMainTitle())) .. " SONG PACK"
		end
	end
	return path
end

